-- ============================================================
-- هزاره‌نامه — امتیاز کیفیت مقاله (برای رتبه‌بندی خودکار با هوش مصنوعی)
-- ============================================================
-- این اسکریپت یک ستون تازه به article_submissions اضافه می‌کند:
--   • ai_quality_score — عددی بین ۰ تا ۱۰۰ که Gemini، جدا از بررسی اصالت
--     (ai_verdict/ai_confidence)، برای قوت و کیفیت محتوای مقاله می‌دهد.
--     این امتیاز پایه‌ی رتبه‌بندی خودکار سه مقام برتر است: از میان مقالاتی
--     که دوره‌ی ۳۰ روزه‌شان تمام شده و اصالت‌شان تأیید شده (verdict =
--     'original')، بالاترین ai_quality_score‌ها به‌عنوان برگزیده انتخاب
--     می‌شوند.
--
-- اجرا: در Supabase SQL Editor کامل بچسبانید و Run بزنید (idempotent).
-- باید بعد از hazaranama-supabase-articles-contest.sql اجرا شود (چون
-- ستون تازه را به جدولی که آن فایل می‌سازد اضافه می‌کند).
-- ============================================================

alter table public.article_submissions
  add column if not exists ai_quality_score numeric;
