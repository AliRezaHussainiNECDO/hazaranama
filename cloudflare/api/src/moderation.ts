/** یکسان‌سازی نوشتار: ی/ك عربی، حذف اعراب، نیم‌فاصله و کشیده، حروف کوچک */
function norm(s: string): string {
  return s
    .toLowerCase()
    .replace(/[يى]/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/[ً-ٰٟـ]/g, "")
    .replace(/[‌‍‎‏]/g, "")
    .replace(/[0@]/g, "o")
    .replace(/[1!|]/g, "i")
    .replace(/\$/g, "s");
}

// واژه‌ها به‌صورت «واژه‌ی کامل» سنجیده می‌شوند تا واژه‌های بی‌گناهی که این حروف را در خود دارند رد نشوند.
const WORDS = [
  // فارسی/دری
  "کیر", "کیری", "کیرم", "جنده", "جندگی", "مادرجنده", "کسکش", "کس‌کش", "کونی", "کونده", "گاییدم", "بگایی", "حرامزاده", "بیناموس", "بی‌ناموس", "پدرسگ", "ننه‌جنده",
  // توهین‌های قومی و نفرت‌پراکنی
  "موشخور", "موش‌خور", "موشخورها", "موشخوران", "موش‌خورها", "خرکار", "چپات", "هزاره‌کش",
  // انگلیسی
  "fuck", "fucking", "fucker", "motherfucker", "shit", "bitch", "cunt", "whore", "slut", "bastard", "dick", "pussy", "nigger", "nigga", "faggot", "retard",
].map(norm);

const PATTERN = new RegExp(`(^|[^\\p{L}\\p{N}])(${WORDS.map((w) => w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|")})(?=$|[^\\p{L}\\p{N}])`, "u");

/** اگر متن واژه‌ی ممنوع داشته باشد، پیام خطا برای کاربر برمی‌گرداند */
export function moderationError(...texts: unknown[]): string | null {
  for (const t of texts) {
    if (typeof t !== "string" || !t) continue;
    if (PATTERN.test(norm(t))) {
      return "متن شما واژه‌های توهین‌آمیز یا نامناسب دارد و منتشر نشد. لطفاً با احترام بنویسید — هزاره‌نامه خانه‌ی همه است.";
    }
  }
  return null;
}
