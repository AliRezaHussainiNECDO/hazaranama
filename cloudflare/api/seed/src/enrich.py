def main():
    figs = load("figures")
    for i, key in FIG.items():
        figs[i - 1]["image"] = image(key)
    dump("figures", figs)

    cul = load("culture")
    for i, key in CUL.items():
        cul[i - 1]["image"] = image(key)
    dump("culture", cul)

    regions = load("map")
    for i, key in MAP_IMG.items():
        regions[i - 1]["image"] = image(key)
    for i, (extra, src) in MAP_FULL.items():
        f = regions[i - 1]["fields"]
        f["full"] = f["note"] + "\n\n" + extra + "\n\n" + src
    dump("map", regions)

    dump("album", [{"fields": {"caption": cap, "desc": desc}, "image": image(key)} for key, cap, desc in ALBUM])

    gen = load("genocide")
    for i, (deaths, src) in GEN.items():
        f = gen[i - 1]["fields"]
        if deaths:
            f["deaths"] = deaths
        if "منبع" not in f["full"][-400:]:
            f["full"] = src_line(f["full"], src)
    for i in UNVERIFIED:
        f = gen[i - 1]["fields"]
        if UNVERIFIED_NOTE not in f["full"]:
            f["full"] = src_line(f["full"], UNVERIFIED_NOTE)
    dump("genocide", gen)

    lib = load("library")
    for i, extra in LIB.items():
        lib[i - 1]["fields"].update(extra)
    dump("library", lib)

    stories = load("dailyStory")
    for s in stories:
        f = s["fields"]
        if f["title"] in OLD_STORY_SRC and "منبع" not in f["full"]:
            f["full"] = src_line(f["full"], OLD_STORY_SRC[f["title"]])
    titles = {s["fields"]["title"] for s in stories}
    for d, t, sub, full in NEW_STORIES:
        if t not in titles:
            stories.append({"fields": {"date": d, "title": t, "desc": sub, "full": full}})
    dump("dailyStory", stories)


if __name__ == "__main__":
    main()
